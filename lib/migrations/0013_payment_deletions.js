// Migration 0013 — the sender's phone number, and a permanent record of
// every deleted transaction.
//
// TWO changes, both about how a payment is identified and accounted for.
//
// 1. payments.sender_phone
//
//    The landlord used to be asked for the MonCash/NatCash transaction
//    ID. They are now asked for the phone number they sent the money
//    from, which is what the admin actually matches against the
//    statement. It is a NEW COLUMN rather than a reuse of `reference`,
//    and that is not tidiness — `reference` carries UNIQUE (provider,
//    reference), so a phone number in it would reject the SECOND
//    quarterly payment any landlord ever made from the same phone. The
//    recurring subscription shipped in 0010 would have broken on its
//    first renewal.
//
//    `reference` is kept, still unique, and is now generated by the
//    server. Nothing is asked of the user for it.
//
// 2. payment_deletions — append-only, and it stays.
//
//    Test transactions have to be removable: a demo payment sitting in
//    confirmed revenue is a lie about the money. But a deletion that
//    leaves no trace is a worse lie, so deleting a payment COPIES the
//    whole row here first, with who deleted it and a mandatory reason.
//
//    "Mandatory" is a CHECK constraint, not a form validation. A reason
//    enforced only in the browser is a reason the next caller forgets,
//    and this is the audit trail for money.
//
//    Nothing in the application deletes from this table — there is no
//    route, no helper, and no admin button that writes a DELETE against
//    it. Its `down()` deliberately does NOT drop it either, which breaks
//    this project's usual "every migration is reversible" rule on
//    purpose: rolling the schema back must not be a way to erase the
//    record of what was erased. Dropping it is a deliberate act by
//    somebody with a psql prompt, which is the only level at which
//    "forever" can honestly be promised.
